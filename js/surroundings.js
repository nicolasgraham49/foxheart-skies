// Climate guess for the rest of the world (land tint only).
export function climateFor(lat, lon) {
  const r = REGIONS.find(r => lat >= r.bbox[0] && lat <= r.bbox[2] && lon >= r.bbox[1] && lon <= r.bbox[3]);
  if (r) return r.climate;
  const al = Math.abs(lat);
  if ((lat > 15 && lat < 33 && lon > -17 && lon < 60) || (lat > 20 && lat < 36 && lon > -118 && lon < -103) || (lat < -18 && lat > -32 && lon > 115 && lon < 145)) return 'desert';
  if (al < 15) return 'tropical';
  if (al < 30) return 'subtropical';
  if (al > 55) return 'boreal';
  return 'temperate';
}
